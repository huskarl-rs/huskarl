/// A [`DPoPNonceChecker`] that issues and validates AEAD-encrypted timestamp nonces.
///
/// Nonces are generated by encrypting the supplied Unix timestamp with an AEAD cipher,
/// then base64url-encoding the result (without padding). This allows stateless verification of nonce age
/// without a database, as long as the encryption key is stable across requests.
/// Ages and lifetimes use whole seconds; a nonce is valid at exactly its lifetime.
/// Future-issued nonces have age zero, including after a backward clock adjustment.
/// A timestamp before the Unix epoch returns a non-retryable error.
#[derive(Debug, Builder)]
pub struct SealedTimestampNonce {
    /// The AEAD sealer/unsealer for nonce timestamps — one object that seals on
    /// the way out and unseals on the way in.
    ///
    /// Wrap an [`AeadCipher`](crate::crypto::cipher::AeadCipher) (a key,
    /// or a rotating stack such as
    /// [`ScheduledRefreshCipher`](crate::crypto::cipher::ScheduledRefreshCipher))
    /// in [`AeadV1Sealer`](crate::crypto::seal::AeadV1Sealer); an
    /// externally-managed sealer (e.g. a KMS encrypt endpoint) can implement
    /// the traits directly.
    ///
    /// The nonce key is long-lived with no natural rotation trigger — prefer a
    /// wide-nonce cipher (XChaCha20-Poly1305, `XC20P`) over AES-GCM's 2^32
    /// per-key encryption budget; see [composing crypto
    /// strategies](crate::_docs::explanation::crypto_strategies).
    #[builder(with = |sealer: impl AeadSealerUnsealer + 'static| Arc::new(sealer) as Arc<dyn AeadSealerUnsealer>)]
    sealer: Arc<dyn AeadSealerUnsealer>,
    /// The maximum age of a valid nonce. Defaults to 1 hour.
    #[builder(into, default = Duration::from_hours(1))]
    nonce_lifetime: Duration,
    /// How far before expiry a still-valid nonce triggers proactive rotation.
    /// Defaults to 15 minutes.
    #[builder(into, default = Duration::from_mins(15))]
    renewal_window: Duration,
    /// AEAD associated data bound into every nonce. The default is fine; change
    /// it only for domain separation, and keep it stable across requests (seal
    /// and unseal must use the same value).
    #[builder(into, default = b"dpop-nonce")]
    aad: Vec<u8>,
}

impl SealedTimestampNonce {
    async fn generate_nonce(&self, now_secs: u64) -> Result<String, Error> {
        use base64::prelude::*;
        let current_time = now_secs.to_be_bytes();
        // `seal` freezes one key snapshot per nonce, even under rotation. The
        // kid is dropped: a nonce is opaque to the client that echoes it back,
        // so unsealing relies on try-all instead.
        let sealed = self.sealer.seal(&current_time, &self.aad).await?;
        Ok(BASE64_URL_SAFE_NO_PAD.encode(sealed.bundle))
    }

    async fn nonce_age_secs(&self, nonce: Option<&str>, now_secs: u64) -> Option<u64> {
        use base64::prelude::*;
        let nonce_bytes = BASE64_URL_SAFE_NO_PAD.decode(nonce?).ok()?;
        let unsealed_bytes = self
            .sealer
            .unseal(&nonce_bytes, &self.aad, None)
            .await
            .ok()?;
        let timestamp_bytes = <[u8; 8]>::try_from(unsealed_bytes).ok()?;
        let nonce_issued_at = u64::from_be_bytes(timestamp_bytes);
        Some(now_secs.saturating_sub(nonce_issued_at))
    }
}

impl DPoPNonceChecker for SealedTimestampNonce {
    fn check_nonce<'a>(
        &'a self,
        nonce: Option<&'a str>,
    ) -> MaybeSendBoxFuture<'a, Result<NonceCheck, Error>> {
        self.check_nonce_at(nonce, crate::time::Clock::now(&crate::time::PlatformClock))
    }

    fn check_nonce_at<'a>(
        &'a self,
        nonce: Option<&'a str>,
        now: jiff::Timestamp,
    ) -> MaybeSendBoxFuture<'a, Result<NonceCheck, Error>> {
        Box::pin(async move {
            let now_secs = crate::time::unix_seconds_from_timestamp(now)
                .map_err(|_| ClockBeforeEpochSnafu.build())?;
            let lifetime = self.nonce_lifetime.as_secs();
            let renewal_threshold = lifetime.saturating_sub(self.renewal_window.as_secs());

            match self.nonce_age_secs(nonce, now_secs).await {
                Some(age) if age <= lifetime => {
                    if age >= renewal_threshold {
                        Ok(NonceCheck::ValidWithNewNonce(
                            self.generate_nonce(now_secs).await?,
                        ))
                    } else {
                        Ok(NonceCheck::Valid)
                    }
                }
                _ => Ok(NonceCheck::Invalid(self.generate_nonce(now_secs).await?)),
            }
        })
    }
}

// This single-shape cause always establishes a terminal classification.
impl crate::error::propagation::Cause for ClockBeforeEpochError {
    fn origin(&self) -> crate::error::propagation::Origin<'_> {
        crate::error::propagation::Origin::Establishes(crate::error::RetryAdvice::No.into())
    }
}

impl From<ClockBeforeEpochError> for Error {
    #[track_caller]
    fn from(source: ClockBeforeEpochError) -> Self {
        Self::from_cause(source)
    }
}

#[cfg(test)]
mod tests {
    use std::borrow::Cow;

    use base64::prelude::*;

    use super::*;
    use crate::crypto::{
        KeyMatchStrength,
        cipher::{AeadEncryptor, AeadOutput, CipherMatch, DecryptError},
        seal::AeadV1Sealer,
    };

    #[derive(Debug)]
    struct MockEncryptor;

    /// XOR "cipher" with both capabilities on one object — the shape a
    /// symmetric key or KMS-backed cipher provides: a selector handing out its
    /// shared inner encryptor, plus a decryptor.
    #[derive(Debug)]
    struct MockCipher {
        inner: Arc<MockEncryptor>,
    }

    impl MockCipher {
        fn new() -> Self {
            Self {
                inner: Arc::new(MockEncryptor),
            }
        }
    }

    impl crate::crypto::cipher::AeadEncryptor for MockEncryptor {
        fn enc_algorithm(&self) -> Cow<'_, str> {
            "mock".into()
        }

        fn key_id(&self) -> Option<Cow<'_, str>> {
            None
        }

        fn encrypt<'a>(
            &'a self,
            plaintext: &'a [u8],
            _aad: &'a [u8],
        ) -> MaybeSendBoxFuture<'a, Result<AeadOutput, Error>> {
            Box::pin(async move {
                Ok(AeadOutput {
                    nonce: vec![1, 2, 3],
                    ciphertext: plaintext.iter().map(|b| b ^ 0xFF).collect(),
                    tag: vec![4, 5, 6, 7],
                })
            })
        }
    }

    impl crate::crypto::cipher::AeadEncryptorSelector for MockCipher {
        fn select_encryptor(&self) -> MaybeSendBoxFuture<'_, Arc<dyn AeadEncryptor>> {
            let snapshot: Arc<dyn AeadEncryptor> = self.inner.clone();
            Box::pin(async move { snapshot })
        }
    }

    impl crate::crypto::cipher::AeadDecryptor for MockCipher {
        fn cipher_match(&self, _m: &CipherMatch<'_>) -> Option<KeyMatchStrength> {
            Some(KeyMatchStrength::ByAlgorithm)
        }

        fn decrypt<'a>(
            &'a self,
            _cipher_match: Option<&'a CipherMatch<'a>>,
            _nonce: &'a [u8],
            ciphertext: &'a [u8],
            _tag: &'a [u8],
            _aad: &'a [u8],
        ) -> MaybeSendBoxFuture<'a, Result<Vec<u8>, DecryptError>> {
            Box::pin(async move { Ok(ciphertext.iter().map(|b| b ^ 0xFF).collect()) })
        }
    }

    fn checker() -> SealedTimestampNonce {
        SealedTimestampNonce::builder()
            .sealer(AeadV1Sealer::new(MockCipher::new()))
            .build()
    }

    fn time() -> crate::time::ManualTime {
        crate::time::ManualTime::new(jiff::Timestamp::new(10_000, 0).unwrap())
    }

    async fn issue(checker: &dyn DPoPNonceChecker, now: jiff::Timestamp) -> String {
        let NonceCheck::Invalid(nonce) = checker.check_nonce_at(None, now).await.unwrap() else {
            panic!("missing nonce must be invalid and issue a replacement");
        };
        nonce
    }

    async fn issued_seconds(checker: &SealedTimestampNonce, nonce: &str) -> u64 {
        let bundle = BASE64_URL_SAFE_NO_PAD.decode(nonce).unwrap();
        let bytes = checker
            .sealer
            .unseal(&bundle, &checker.aad, None)
            .await
            .unwrap();
        u64::from_be_bytes(bytes.try_into().unwrap())
    }

    #[tokio::test]
    async fn issuance_and_forwarding_preserve_timestamp() {
        use crate::time::Clock;
        let time = time();
        let checker = Arc::new(checker());
        // Exercise Arc, Box, and reference forwarding through trait objects.
        let boxed: Box<dyn DPoPNonceChecker> = Box::new(checker.clone());
        let borrowed: &dyn DPoPNonceChecker = &boxed;
        let nonce = issue(&borrowed, time.now()).await;
        assert_eq!(issued_seconds(&checker, &nonce).await, 10_000);
        assert_eq!(
            checker
                .check_nonce_at(Some(&nonce), time.now())
                .await
                .unwrap(),
            NonceCheck::Valid
        );
        assert!(matches!(
            checker
                .check_nonce_at(Some("not-a-nonce"), time.now())
                .await
                .unwrap(),
            NonceCheck::Invalid(_)
        ));
    }

    #[tokio::test]
    async fn renewal_and_expiry_use_whole_second_boundaries() {
        use crate::time::Clock;
        let time = time();
        let checker = checker();
        let nonce = issue(&checker, time.now()).await;
        // One nanosecond before the 2700-second renewal threshold.
        time.advance(Duration::from_mins(45) - Duration::from_nanos(1))
            .unwrap();
        assert_eq!(
            checker
                .check_nonce_at(Some(&nonce), time.now())
                .await
                .unwrap(),
            NonceCheck::Valid
        );
        time.advance(Duration::from_nanos(1)).unwrap();
        let NonceCheck::ValidWithNewNonce(replacement) = checker
            .check_nonce_at(Some(&nonce), time.now())
            .await
            .unwrap()
        else {
            panic!("renewal starts at the exact threshold");
        };
        assert_eq!(issued_seconds(&checker, &replacement).await, 12_700);
        assert_eq!(
            checker
                .check_nonce_at(Some(&replacement), time.now())
                .await
                .unwrap(),
            NonceCheck::Valid
        );
        // Exactly the lifetime, and the remainder of that second, are valid.
        time.advance(Duration::from_mins(15)).unwrap();
        assert!(matches!(
            checker
                .check_nonce_at(Some(&nonce), time.now())
                .await
                .unwrap(),
            NonceCheck::ValidWithNewNonce(_)
        ));
        time.advance(Duration::from_nanos(999_999_999)).unwrap();
        assert!(matches!(
            checker
                .check_nonce_at(Some(&nonce), time.now())
                .await
                .unwrap(),
            NonceCheck::ValidWithNewNonce(_)
        ));
        time.advance(Duration::from_nanos(1)).unwrap();
        let NonceCheck::Invalid(replacement) = checker
            .check_nonce_at(Some(&nonce), time.now())
            .await
            .unwrap()
        else {
            panic!("nonce must expire after its whole-second lifetime");
        };
        assert_eq!(issued_seconds(&checker, &replacement).await, 13_601);
    }

    #[tokio::test]
    async fn backward_clock_and_extreme_timestamps_do_not_overflow() {
        use crate::time::Clock;
        let time = time();
        let checker = checker();
        let nonce = issue(&checker, time.now()).await;
        time.set_wall_time(jiff::Timestamp::UNIX_EPOCH);
        assert_eq!(
            checker
                .check_nonce_at(Some(&nonce), time.now())
                .await
                .unwrap(),
            NonceCheck::Valid
        );
        let epoch_nonce = issue(&checker, time.now()).await;
        assert_eq!(issued_seconds(&checker, &epoch_nonce).await, 0);
        time.set_wall_time(jiff::Timestamp::MAX);
        let NonceCheck::Invalid(replacement) = checker
            .check_nonce_at(Some(&epoch_nonce), time.now())
            .await
            .unwrap()
        else {
            panic!("epoch nonce must be expired at the maximum timestamp");
        };
        assert_eq!(
            issued_seconds(&checker, &replacement).await,
            jiff::Timestamp::MAX.as_second().cast_unsigned()
        );
        assert_eq!(
            checker
                .check_nonce_at(Some(&replacement), time.now())
                .await
                .unwrap(),
            NonceCheck::Valid
        );
        for before_epoch in [
            jiff::Timestamp::new(-1, 999_999_999).unwrap(),
            jiff::Timestamp::MIN,
        ] {
            time.set_wall_time(before_epoch);
            for presented in [None, Some(nonce.as_str()), Some("garbage")] {
                let err = checker
                    .check_nonce_at(presented, time.now())
                    .await
                    .unwrap_err();
                assert_eq!(err.retry_advice(), crate::RetryAdvice::No);
                assert!(format!("{err:#}").contains("before the Unix epoch"));
            }
        }
    }
}

#[cfg(test)]
mod compatibility_tests {
    use super::*;

    struct Legacy;
    impl DPoPNonceChecker for Legacy {
        fn check_nonce<'a>(
            &'a self,
            nonce: Option<&'a str>,
        ) -> MaybeSendBoxFuture<'a, Result<NonceCheck, Error>> {
            Box::pin(async move { Ok(NonceCheck::Invalid(nonce.unwrap_or_default().to_owned())) })
        }
    }

    struct TimestampAware;
    impl DPoPNonceChecker for TimestampAware {
        fn check_nonce<'a>(
            &'a self,
            _nonce: Option<&'a str>,
        ) -> MaybeSendBoxFuture<'a, Result<NonceCheck, Error>> {
            panic!("forwarding must preserve the timestamp-aware override")
        }
        fn check_nonce_at<'a>(
            &'a self,
            _nonce: Option<&'a str>,
            now: jiff::Timestamp,
        ) -> MaybeSendBoxFuture<'a, Result<NonceCheck, Error>> {
            Box::pin(async move { Ok(NonceCheck::Invalid(now.as_second().to_string())) })
        }
    }

    #[tokio::test]
    async fn legacy_fallback_and_pointer_forwarding() {
        let now = jiff::Timestamp::new(123, 0).unwrap();
        let legacy: Arc<dyn DPoPNonceChecker> = Arc::new(Legacy);
        assert_eq!(
            legacy.check_nonce_at(Some("legacy"), now).await.unwrap(),
            NonceCheck::Invalid("legacy".into())
        );
        let aware: Arc<Box<&dyn DPoPNonceChecker>> = Arc::new(Box::new(&TimestampAware));
        assert_eq!(
            aware.check_nonce_at(None, now).await.unwrap(),
            NonceCheck::Invalid("123".into())
        );
    }
}
